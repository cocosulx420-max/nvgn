function Clean.fromLocal(data: any, cfg: Config?)
	local c = merged(cfg)
	local t0 = os.clock()
	local samples, sstats = sampleFrontier(data, c)
	local raw = buildRuns(samples, c)
	local edges, report = closeAll(raw, data, c)
	edges = bridgeDeferred(edges, data, c, report)

	local byClass, studs = {}, {}
	for _, k in ipairs({ "wall", "seam", "dropoff", "tier" }) do byClass[k] = 0; studs[k] = 0 end
	for _, e in ipairs(edges) do
		byClass[e.class] += 1
		studs[e.class] += (e.b - e.a).Magnitude
	end
	return {
		edges = edges, samples = samples, config = c,
		stats = {
			samples = sstats, rawRuns = #raw, edges = #edges,
			byClass = byClass, studs = studs, closure = report,
			seconds = os.clock() - t0,
		},
	}
end

function Clean.build(cfg: Config?)
	local data, floorData, tree, parts = LocalGrid.build(cfg)
	return Clean.fromLocal(data, cfg), data, floorData, tree, parts
end

