local function bar(parent: Instance, a: Vector3, b: Vector3, colour: Color3, thick: number, name: string)
	local d = b - a
	local len = d.Magnitude
	if len < 1e-3 then return end
	local p = Instance.new("Part")
	p.Anchored = true; p.CanCollide = false; p.CanQuery = false; p.CanTouch = false
	p.Size = Vector3.new(len, thick, thick)
	p.Color = colour
	p.Material = Enum.Material.Neon
	p.CFrame = CFrame.fromMatrix((a + b) * 0.5, d.Unit, UP)
	p.Name = name
	p.Parent = parent
end

-- red = wall / green = seam / cyan = dropoff / yellow = tier.
-- `showOpen` balls any endpoint that failed to close, which is the only thing
-- loop assembly will care about.
function Clean.visualize(result: any, parent: Instance?, showOpen: boolean?)
	local root = parent or workspace
	local dbg = root:FindFirstChild("NVGN_Debug")
	if not dbg then dbg = Instance.new("Folder"); dbg.Name = "NVGN_Debug"; dbg.Parent = root end
	local old = dbg:FindFirstChild("Clean")
	if old then old:Destroy() end
	local folder = Instance.new("Folder"); folder.Name = "Clean"; folder.Parent = dbg

	local colours = {
		wall = Color3.new(1, 0.15, 0.15),
		seam = Color3.new(0.2, 1, 0.35),
		dropoff = Color3.new(0.15, 0.9, 1),
		tier = Color3.new(0.95, 0.85, 0.1),
	}
	for _, e in ipairs(result.edges) do
		-- nudged toward the walkable side: an edge drawn fractionally inside a
		-- wall face looks exactly like a missing edge (v1 round 12)
		local off = UP * 0.06 - e.outDir * 0.04
		local col, nm = colours[e.class], e.class
		if e.provisional then
			-- stands in for a deferred neighbour's missing boundary: dimmed so
			-- it never reads as measured geometry
			col = col:Lerp(Color3.new(0, 0, 0), 0.55)
			nm = e.class .. "_provisional"
		end
		bar(folder, e.a + off, e.b + off, col, 0.3, nm)
		if showOpen then
			-- only genuine holes get a marker; a handover is where the region
			-- continues onto an overlapping slab, which loop assembly stitches
			local ends = {
				{ e.a, e.closedA or e.handoverA },
				{ e.b, e.closedB or e.handoverB },
			}
			for _, pair in ipairs(ends) do
				if not pair[2] then
					local ball = Instance.new("Part")
					ball.Shape = Enum.PartType.Ball
					ball.Anchored = true; ball.CanCollide = false; ball.CanQuery = false
					ball.Size = Vector3.new(0.5, 0.5, 0.5)
					ball.Color = Color3.new(1, 1, 1)
					ball.Material = Enum.Material.Neon
					ball.Position = pair[1] :: Vector3
					ball.Name = "open"
					ball.Parent = folder
				end
			end
		end
	end
	return folder
end

return Clean
